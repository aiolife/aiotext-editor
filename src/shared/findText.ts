/**
 * 查找框预填的文字处理（F-05 §5.3）。
 *
 * 抽到 shared 而不是留在面板组件里：转义规则（尤其是换行）很容易与后端
 * 正则的真实行为脱节，得有一处能单测钉住的地方。
 */

/**
 * 选区自动填进查找框的长度上限。
 * 超了就当没选 —— 那么长多半是误选了整篇，填进去既卡也没意义。
 */
export const SELECTION_FILL_LIMIT = 600;

/**
 * 选中的文字进查找框之前的转义。
 *
 * 两件事：正则元字符逐个转义（选中 `a(b` 直接查会报错）；
 * 真实换行转成字面的 `\n` —— 跨行 / 跨段的选区塞不进单行输入框，
 * 而后端认的是正则，所以这种情况得把面板一并切成正则模式。
 *
 * **返回值与原文不同，就说明需要切到正则模式**（调用方据此判断）。
 */
export function escapeForFind(text: string): string {
  return text
    .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    .replace(/\r\n/g, '\n')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\n')
    .replace(/\t/g, '\\t');
}
